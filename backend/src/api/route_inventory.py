"""The REST route inventory, read from the routers themselves.

`docs/backend/api-reference.md` carries a generated "Route index" section (between the
`ROUTES_BEGIN`/`ROUTES_END` markers) built from this module, so the documented surface cannot drift
from the code: `tests/api/test_api_reference_sync.py` fails when a route exists without a row.

This module only reads the routers and renders text; it never writes a file. To refresh the
document after adding, removing or renaming a route, run the sync test in update mode:

    cd backend && UPDATE_API_REFERENCE=1 uv run pytest tests/api/test_api_reference_sync.py
"""

from __future__ import annotations

import importlib
import inspect
import re
from dataclasses import dataclass
from pathlib import Path
from typing import TYPE_CHECKING

from fastapi.routing import APIRoute

if TYPE_CHECKING:
    from collections.abc import Iterator

    from fastapi.dependencies.models import Dependant

API_PREFIX = "/api/v1"
ROUTES_BEGIN = "<!-- ROUTES:BEGIN (generated by tests/api/test_api_reference_sync.py) -->"
ROUTES_END = "<!-- ROUTES:END -->"

# (module under api.routers, section title, mounted under API_PREFIX?) in api/app.py order.
ROUTER_SECTIONS: tuple[tuple[str, str, bool], ...] = (
    ("context", "Context, quotes & source health", True),
    ("market", "Quotes & live streams", True),
    ("market_rest.market", "Market, stock-detail, derivatives & macro data", True),
    ("market_rest.symbols", "Market, stock-detail, derivatives & macro data", True),
    ("market_rest.macro_news", "Market, stock-detail, derivatives & macro data", True),
    ("market_rest.stock", "Market, stock-detail, derivatives & macro data", True),
    ("analytics", "Analytics, scoring & screener", True),
    ("themes", "Themes & supply chain", True),
    ("fund_data", "Funds, analysts & ETF overlap", True),
    ("agent", "Agent turns", True),
    ("threads", "Threads", True),
    ("threads_actions", "Thread & turn actions", True),
    ("voice", "Voice", True),
    ("memory", "Memory & watchlists", True),
    ("pets", "Pets", True),
    ("auth", "Auth & OAuth", True),
    ("accounts_extra", "Account, BYOK keys & usage", True),
    ("billing", "Billing (Paddle)", True),
    ("scheduler", "Alerts, schedules, notifications & channels", True),
    ("probes", "Ops probes (app root, not under /api/v1)", False),
)

_TOOL_NAME = re.compile(r'"((?:get|run|search|build|propose)_[a-z0-9_]+)"')
_BACKED_BY_MARKER = "backed by `"
_SUMMARY_MAX = 150


@dataclass(frozen=True)
class RouteRow:
    section: str
    method: str
    path: str
    auth: str  # "user" (require_user), "optional" (optional_user), or "none"
    tools: tuple[str, ...]
    tier: str  # data class of the backing tool(s), "" when none
    summary: str


def _dependency_names(dependant: Dependant) -> Iterator[str]:
    for sub in dependant.dependencies:
        if sub.call is not None:
            yield getattr(sub.call, "__name__", "")
        yield from _dependency_names(sub)


def _auth_of(dependant: Dependant) -> str:
    names = set(_dependency_names(dependant))
    if "require_user" in names:
        return "user"
    if "optional_user" in names:
        return "optional"
    return "none"


def _summary(endpoint: object, fn_name: str) -> str:
    """First sentence of the endpoint docstring, minus the 'backed by `tool`' tail the tool column
    already shows, cut to one table-friendly line. Falls back to the handler name in words."""
    doc = inspect.getdoc(endpoint) or ""
    if not doc:
        return fn_name.replace("_", " ").strip().capitalize()
    paragraph = " ".join(doc.split("\n\n", 1)[0].split())
    cut = paragraph.find(_BACKED_BY_MARKER)
    if cut >= 0:
        paragraph = paragraph[:cut].rstrip(" ,—-")
    sentence = re.split(r"(?<=[.。])\s", paragraph, maxsplit=1)[0]
    if len(sentence) > _SUMMARY_MAX:
        sentence = sentence[: _SUMMARY_MAX - 1].rstrip() + "…"
    return sentence.replace("|", "\\|")


def _endpoint_source(module_file: Path, fn_name: str) -> str:
    source = module_file.read_text(encoding="utf-8")
    start = source.find(f"def {fn_name}(")
    if start < 0:
        return ""
    end = source.find("\n@router.", start + 1)
    return source[start : end if end >= 0 else len(source)]


def _tool_tiers() -> dict[str, str]:
    """`tool name -> data class` for every registered tool class, read off the classes."""
    import tools  # noqa: PLC0415 — the interface layer may import tools; deferred to call time
    from tools.base import BaseTool  # noqa: PLC0415

    importlib.import_module(tools.__name__)
    tiers: dict[str, str] = {}
    pending: list[type[BaseTool]] = list(BaseTool.__subclasses__())
    while pending:
        cls = pending.pop()
        pending.extend(cls.__subclasses__())
        name = getattr(cls, "name", None)
        data_class = getattr(cls, "data_class", None)
        if isinstance(name, str) and data_class is not None:
            tiers[name] = str(getattr(data_class, "value", data_class))
    return tiers


def route_rows() -> list[RouteRow]:
    tiers = _tool_tiers()
    rows: list[RouteRow] = []
    for module_name, section, prefixed in ROUTER_SECTIONS:
        module = importlib.import_module(f"api.routers.{module_name}")
        module_file = Path(inspect.getfile(module))
        for route in module.router.routes:
            if not isinstance(route, APIRoute):
                continue
            tools = tuple(
                sorted(set(_TOOL_NAME.findall(_endpoint_source(module_file, route.name))))
            )
            tool_tiers = sorted({tiers[t] for t in tools if t in tiers})
            path = f"{API_PREFIX}{route.path}" if prefixed else route.path
            rows.extend(
                RouteRow(
                    section=section,
                    method=method,
                    path=path,
                    auth=_auth_of(route.dependant),
                    tools=tools,
                    tier="/".join(tool_tiers),
                    summary=_summary(route.endpoint, route.name),
                )
                for method in sorted((route.methods or set()) - {"HEAD", "OPTIONS"})
            )
    return rows


def render_markdown(rows: list[RouteRow]) -> str:
    lines = [
        ROUTES_BEGIN,
        "",
        f"{len(rows)} routes. **Auth**: `user` = sign-in required (401 otherwise); `optional` = "
        "anonymous allowed, the caller's tier applies when signed in; `none` = no auth "
        "dependency (probes, webhooks verified by signature, OAuth). **Tier** is the backing "
        "tool's data class: `sponsor` data is masked for unentitled callers with the HTTP 200 "
        "teaser envelope.",
        "",
    ]
    current = ""
    for row in rows:
        if row.section != current:
            current = row.section
            lines += [
                "",
                f"#### {current}",
                "",
                "| Method | Path | Auth | Tool | Tier | Summary |",
                "|---|---|---|---|---|---|",
            ]
        tools = ", ".join(f"`{t}`" for t in row.tools) or "—"
        lines.append(
            f"| {row.method} | `{row.path}` | {row.auth} | {tools} | {row.tier or '—'} | "
            f"{row.summary or '—'} |"
        )
    lines += ["", ROUTES_END]
    return "\n".join(lines)


def splice(document: str, generated: str) -> str:
    begin = document.find(ROUTES_BEGIN)
    end = document.find(ROUTES_END)
    if begin < 0 or end < 0:
        msg = "route-index markers not found in the API reference"
        raise ValueError(msg)
    return document[:begin] + generated + document[end + len(ROUTES_END) :]


def reference_path() -> Path:
    return Path(__file__).resolve().parents[3] / "docs" / "backend" / "api-reference.md"


